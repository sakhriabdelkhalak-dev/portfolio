const assert = require('node:assert/strict');
const C = require('../demos/cap-pro/core.js');
const today = '2026-11-01';
const records = C.demoRecords(new Date(2026,10,1));
assert.deepEqual(C.metrics(records,today),{total:6,pending:4,interviews:1,due:2,trash:0});
assert.equal(C.isoDate(new Date(2026,10,1,0,5)),today,'Use local calendar dates, not UTC offsets');
assert.equal(C.validDate('2024-02-29'),true);
assert.equal(C.validDate('2026-02-29'),false);
assert.equal(C.validDate('2026-04-31'),false);
assert.equal(C.visible(records,{query:'equipe',today})[0].company,'Équipe Latitude','Search ignores accents');
assert.equal(C.visible(records,{nav:'due',today}).length,2);
assert.equal(C.visible(records,{nav:'interview',today}).length,1);
assert.equal(C.visible(records,{status:'closed',today}).length,1);
assert.equal(C.visible(records,{query:'aucun résultat',today}).length,0);
assert.equal(C.visible(records,{sort:'followup',today}).at(-1).company,'Équipe Latitude','Unscheduled records sort last');
const trashed=records.map((record,index)=>index===0?{...record,deletedAt:today}:record);
assert.equal(C.visible(trashed,{today}).length,5);
assert.equal(C.visible(trashed,{nav:'trash',today}).length,1);
assert.equal(C.metrics(trashed,today).interviews,0);
assert.equal(C.metrics(trashed,today).trash,1);
const restored=trashed.map(record=>({...record,deletedAt:null}));
assert.deepEqual(C.metrics(restored,today),C.metrics(records,today));
for(const status of ['closed','offer','draft']) assert.equal(C.due({...records[1],status},today),false);
assert.throws(()=>C.normalize({...records[0],company:'  '}),/entreprise/);
assert.throws(()=>C.normalize({...records[0],status:'unknown'}),/statut/);
assert.throws(()=>C.normalize({...records[0],followUp:'2026-01-01'}),/relance/);
assert.throws(()=>C.normalize({...records[0],url:'javascript:alert(1)'}),/http/);
assert.throws(()=>C.normalize({...records[0],url:'data:text/html,test'}),/http/);
const https=C.normalize({...records[0],url:'https://example.com/offre?q=web&ville=rabat'});
assert.equal(https.url,'https://example.com/offre?q=web&ville=rabat');
const csv=C.toCSV([{...records[0],company:'=SUM(1;2)',notes:'Une "citation"\navec une seconde ligne'}]);
assert.ok(csv.startsWith('\ufeff'));
assert.ok(csv.includes('"\'=SUM(1;2)"'),'User values must not become spreadsheet formulas');
assert.ok(csv.includes('"Une ""citation""\navec une seconde ligne"'),'Quotes and newlines must survive CSV export');
assert.equal(C.normalize({...records[0],company:'  Exemple  '}).company,'Exemple');
console.log('Cap Pro passed: dashboard counts, local dates, leap years, reminders, accent search, sorting, filters, trash/restore, validation, safe links and CSV escaping.');
