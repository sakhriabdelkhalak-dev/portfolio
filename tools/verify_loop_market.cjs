const assert=require('node:assert/strict');
const M=require('../demos/loop-market/catalog.js');
assert.equal(M.PRODUCTS.length,6);
assert.equal(new Set(M.PRODUCTS.map(p=>p.id)).size,6);
assert.deepEqual(M.normalizeCart([{id:'pulse',quantity:4},{id:'pulse',quantity:5},{id:'unknown',quantity:1},{id:'solo',quantity:-1}]),[{id:'pulse',quantity:6}]);
assert.throws(()=>M.normalizeCart({}));
assert.throws(()=>M.add([], 'unknown'));
assert.throws(()=>M.add([], 'pulse',7));
assert.throws(()=>M.add([], 'pulse',1.5));
const cart=M.add([], 'pulse',2);assert.equal(cart[0].quantity,2);
assert.deepEqual(M.setQuantity(cart,'pulse',0),[]);assert.equal(cart[0].quantity,2);
assert.throws(()=>M.setQuantity(cart,'pulse',-1));
assert.equal(M.totals([]).total,0);
assert.equal(M.totals([{id:'solo',quantity:1}]).total,11400);
const below=M.totals([{id:'pulse',quantity:1},{id:'arc',quantity:1}]);
assert.equal(below.subtotal,47800);assert.equal(below.shipping,2500);assert.equal(below.total,50300);
assert.equal(M.totals([{id:'pulse',quantity:1},{id:'tempo',quantity:1}]).shipping,0);
assert.deepEqual(M.filter({query:'ecouteurs'}).map(p=>p.id),['solo']);
assert.equal(M.filter({category:'studio'}).length,2);
assert.equal(M.filter({maxPrice:8800}).length,0);
assert.equal(M.filter({sort:'price-asc'})[0].id,'solo');
assert.equal(M.filter({sort:'price-desc'})[0].id,'keys');
assert.deepEqual(M.toggleFavorite(['solo'],'solo'),[]);
assert.deepEqual(M.favorites(['solo','solo','unknown']),['solo']);
assert.deepEqual(M.filter({favoritesOnly:true,favorites:['arc']}).map(p=>p.id),['arc']);
console.log('Loop Market passed: cart validation, stock limits, integer totals, shipping, search, filters, sort and favorites.');
